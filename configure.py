def command(path):
    """PATH quoted for the platform's command line (ninja runs commands without a shell on Windows)."""
    return subprocess.list2cmdline([path]) if os.name == "nt" else shlex.quote(path)


def escape(path):
    """PATH in a ninja build statement."""
    return str(path).replace("$", "$$").replace(" ", "$ ").replace(":", "$:")


def percent(part, whole):
    return 100 * part / whole if whole else 0


def progress(version):
    """Print the totals of build/VERSION/report.json, as dtk-template's projects do after each build. (Data is not
    split per unit yet, so objdiff counts all of it as matched: it is left out.)"""
    report = json.loads(Path(f"build/{version}/report.json").read_text())
    names = {category["id"]: category["name"] for category in report.get("categories", [])}

    def show(name, measures):
        value = lambda key: int(measures.get(key, 0))
        code, units = value("total_code"), value("total_units")
        print(f"  {name}: {measures.get('fuzzy_match_percent', 0):.2f}% matched, "
              f"{percent(value('complete_code'), code):.2f}% complete "
              f"({value('complete_units')} / {units} files)")
        print(f"    Code: {value('matched_code')} / {code} bytes "
              f"({value('matched_functions')} / {value('total_functions')} functions)")

    print("Progress:")
    show("All", report["measures"])
    for category in report.get("categories", []):
        show(names[category["id"]], category["measures"])


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("command", nargs="?", choices=["progress"])
    parser.add_argument("--version", choices=VERSIONS, default=VERSIONS[0])
    parser.add_argument("--vc6", default=os.environ.get("VC6_DIR", ""),
                        help="Visual C++ 6.0 SP6's install root, holding VC98 (default: $VC6_DIR)")
    args = parser.parse_args()
    version = args.version
    if args.command == "progress":
        progress(version)
        return
    config = json.loads(Path(f"config/{version}/config.json").read_text())
    _, units = read_splits(f"config/{version}/splits.txt")
    objdiff_cli = "build/tools/objdiff-cli" + (".exe" if os.name == "nt" else "")

    objects = {}
    for lib in LIBS:
        for obj in lib["objects"]:
            if obj["name"] in objects:
                raise SystemExit(f"configure.py: {obj['name']} is listed twice")
            objects[obj["name"]] = (obj, lib)
    # (code no source file is named for: tools/fill_splits.py names these units auto/<category>/<address>.cpp)
    for unit, _ in units:
        if unit.startswith("auto/") and unit not in objects:
            category = unit.split("/")[1]
            objects[unit] = (Object(NonMatching, unit), {"lib": "auto", "category": category, "auto": True})
    missing = [unit for unit, _ in units if unit not in objects]
    if missing:
        raise SystemExit("configure.py: splits.txt units not in LIBS: " + ", ".join(missing))

    reconfigure = f"configure.py --version {version}" + (f" --vc6 {command(args.vc6)}" if args.vc6 else "")
    out = [
        "# Generated by configure.py",
        f"python = {command(sys.executable)}",
        f"vc6 = {command(args.vc6) if args.vc6 else chr(34) * 2}",
        f"version = {version}",
        "",
        "rule download",
        "  command = $python tools/download_tool.py $tool $out",
        "  description = DOWNLOAD $out",
        "rule split",
        "  command = $python tools/split.py $version",
        "  description = SPLIT $version",
        "rule cc",
        "  command = $python tools/cl.py $vc6 $out $in $cflags",
        "  description = CL $in",
        "  depfile = $out.d",
        "  deps = gcc",
        "rule check",
        "  command = $python tools/check.py config/$version $in $out",
        "  description = CHECK $in",
        "rule report",
        # (CreateProcess does not take a program's relative path with forward slashes)
        f"  command = {command(str(Path(objdiff_cli)))} report generate -o $out",
        "  description = REPORT $out",
        "rule progress",
        "  command = $python configure.py progress --version $version",
        "  description = PROGRESS",
        "rule configure",
        f"  command = $python {reconfigure}",
        "  description = CONFIGURE",
        "  generator = 1",
        "",
        f"build {objdiff_cli}: download",
        "  tool = objdiff-cli",
    ]
    targets, bases, checks, entries = [], [], [], []
    for unit, _ in units:
        obj, lib = objects[unit]
        stem = Path(unit).with_suffix("").as_posix()
        target = f"build/{version}/obj/{stem}.obj"
        targets.append(target)
        source = Path("src") / unit
        if obj["status"] == Matching and not source.is_file():
            raise SystemExit(f"configure.py: {unit} is Matching but {source.as_posix()} does not exist")
        metadata = {
            "complete": obj["status"] == Matching,
            "progress_categories": [lib["category"]],
            "auto_generated": lib.get("auto", False),
        }
        entry = {"name": stem, "target_path": target}
        if source.is_file():
            base = f"build/{version}/src/{stem}.obj"
            bases.append(base)
            flags = obj.get("cflags", lib.get("cflags", config["cflags"]))
            out += [f"build {escape(base)}: cc {escape(source.as_posix())} | tools/cl.py",
                    f"  cflags = {' '.join(flags)}"]
            if obj["status"] == Matching:
                check = f"build/{version}/check/{stem}.ok"
                checks.append(check)
                out.append(f"build {escape(check)}: check {escape(target)} {escape(base)} | tools/check.py "
                           f"tools/pe.py config/{version}/symbols.txt config/{version}/folded.txt")
            entry["base_path"] = base
            metadata["source_path"] = source.as_posix()
        entry["metadata"] = metadata
        entries.append(entry)

    report = f"build/{version}/report.json"
    out += [
        f"build build/{version}/obj/ok {' '.join(map(escape, targets))}: split | tools/split.py tools/pe.py "
        f"{escape(config['original'])} config/{version}/symbols.txt config/{version}/splits.txt",
        f"build {report}: report build/{version}/obj/ok {' '.join(map(escape, bases))} | {objdiff_cli} objdiff.json",
        f"build report: phony {report}",
        # (never written, so it runs on every build)
        f"build progress: progress {report}",
        f"build build.ninja objdiff.json: configure | configure.py tools/split.py "
        f"config/{version}/config.json config/{version}/splits.txt",
        "",
        f"default build/{version}/obj/ok {' '.join(map(escape, bases + checks))} progress",
        "",
    ]
    Path("build.ninja").write_text("\n".join(out))
    Path("objdiff.json").write_text(json.dumps({
        "$schema": "https://raw.githubusercontent.com/encounter/objdiff/main/config.schema.json",
        "min_version": "3.0.0",
        "custom_make": "ninja",
        "build_target": False,
        "build_base": True,
        "watch_patterns": ["src/**/*.c", "src/**/*.cpp", "src/**/*.h", "include/**/*.h", "config/**/*.json",
                           "config/**/*.txt"],
        "units": entries,
        "progress_categories": [{"id": id, "name": name} for id, name in CATEGORIES.items()],
    }, indent=2) + "\n")
    statuses = [objects[unit][0]["status"] for unit, _ in units]
    print(f"{len(units)} of {len(objects)} units located, {len(bases)} with a source, "
          f"{statuses.count(Matching)} Matching")


if __name__ == "__main__":
    main()
